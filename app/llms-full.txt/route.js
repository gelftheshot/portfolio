import { profile } from "@/lib/profile";
import { upwork } from "@/lib/upwork";
import { CONTACT_EMAIL } from "@/lib/contact";
import { absoluteUrl, contentUpdated } from "@/lib/site";
import { buildAssistantKnowledge } from "@/lib/assistant-knowledge";

export const dynamic = "force-static";

function paragraphs(value) {
  return Array.isArray(value) ? value : value ? [value] : [];
}

function projectLines(project) {
  return [
    `### ${project.title}`,
    "",
    `Case study: ${absoluteUrl(`/projects/${project.slug}`)}`,
    `Category: ${project.category}`,
    `Role: ${project.role || "Software engineering"}`,
    "",
    project.description,
    "",
    ...paragraphs(project.detail).flatMap((paragraph) => [paragraph, ""]),
    ...(project.caseStudy ? [
      "#### Role and scope",
      "",
      project.caseStudy.roleContext,
      "",
      "#### Project challenge",
      "",
      project.caseStudy.challenge,
      "",
      "#### Engineering context",
      "",
      project.caseStudy.engineeringContext,
      ...(project.caseStudy.architecture ? [
        `Explanatory diagram: ${absoluteUrl(project.caseStudy.architecture.src)}`,
        project.caseStudy.architecture.alt,
        project.caseStudy.architecture.caption,
      ] : []),
      "",
      "#### Evidence scope",
      "",
      project.caseStudy.evidenceSummary,
      "",
    ] : []),
    ...(project.tags?.length ? [`Technical focus: ${project.tags.join(", ")}.`, ""] : []),
    ...(project.stack ? [`Technology: ${paragraphs(project.stack).join(", ")}`, ""] : []),
    ...(project.website ? [`Website: ${project.website}`] : []),
    ...(project.github ? [`Source repository: ${project.github}`] : []),
    "",
    ...(project.technicalSections || []).flatMap((section) => [
      `#### ${section.title}`,
      "",
      ...paragraphs(section.body).flatMap((paragraph) => [paragraph, ""]),
      ...(section.bullets || []).map((bullet) => `- ${bullet}`),
      "",
    ]),
    ...(project.sources?.length ? [
      "#### References",
      "",
      ...project.sources.flatMap((source) => [
        source.url ? `- [${source.title}](${source.url})` : `- ${source.title}`,
        ...(source.note ? [`  ${source.note}`] : []),
      ]),
      "",
    ] : []),
    ...(project.sourceBoundaries?.length ? [
      "#### Attribution and evidence boundaries",
      "",
      ...project.sourceBoundaries.map((boundary) => `- ${boundary}`),
      "",
    ] : []),
  ];
}

export function GET() {
  const knowledge = buildAssistantKnowledge();
  const text = [
    `# ${profile.name} — Public portfolio`,
    "",
    `${profile.title} · ${profile.location}`,
    `Portfolio: ${absoluteUrl("/")}`,
    `Content updated: ${contentUpdated}`,
    "Source: owner-maintained professional profile and project case studies published on this portfolio. Project-specific references are included below.",
    `Client work source: ${upwork.source.name} public profile (${upwork.source.profileUrl}); snapshot retrieved ${upwork.source.retrievedAt}.`,
    "",
    "## How to interpret this profile",
    "",
    ...knowledge.knownLimitations.map((limitation) => `- ${limitation}`),
    "",
    "## Professional profile",
    "",
    profile.summary,
    "",
    ...(profile.introduction ? ["Homepage introduction:", profile.introduction, ""] : []),
    ...(profile.about ? ["About:", profile.about, ""] : []),
    ...profile.professionalFocus.map((focus) => `- ${focus}`),
    "",
    "## Skills",
    "",
    ...Object.entries(profile.skills).flatMap(([category, skills]) => [
      `### ${category}`,
      "",
      ...skills.map((skill) => `- ${skill}`),
      "",
    ]),
    "## Engineering expertise",
    "",
    ...profile.expertise.flatMap((area) => [
      `### ${area.title}`,
      "",
      area.description,
      `Tools and focus: ${area.tools}`,
      "",
    ]),
    "## Automation focus",
    "",
    profile.automationFocus.summary,
    "",
    ...profile.automationFocus.focusAreas.map((area) => `- ${area}`),
    "",
    ...profile.automationFocus.projectEvidence.map((project) => `- [${project.title}](${absoluteUrl(`/projects/${project.slug}`)}): ${project.description}`),
    "",
    "## Employment history",
    "",
    ...profile.experience.flatMap((item) => [
      `### ${item.role} — ${item.company}`,
      "",
      `Period: ${item.period}`,
      `Portfolio role: ${absoluteUrl(`/#${item.id}`)}`,
      "",
      item.description,
      ...(item.scopeNote ? [item.scopeNote] : []),
      "",
      ...(item.tools ? [`Tools: ${item.tools}`, ""] : []),
      ...item.responsibilities.flatMap((area) => [
        `#### ${area.title}`,
        "",
        area.description,
        "",
      ]),
      `Engineering focus: ${item.focusAreas.join(", ")}.`,
      "",
    ]),
    "## Education",
    "",
    ...profile.education.map((item) => `- ${item.degree} — ${item.institution}`),
    "",
    "## Listed training credentials",
    "",
    ...(profile.certifications || []).flatMap((credential) => [
      `### ${credential.name}`,
      "",
      `Provider: ${credential.provider}. Issued: ${credential.issued}.${credential.expires ? ` Expires: ${credential.expires}.` : ""}`,
      `Credential link: ${credential.url}`,
      `Listing source: ${credential.source.name} (${credential.source.url}); checked ${credential.source.checkedAt}.`,
      credential.verification,
      "",
    ]),
    "## Languages",
    "",
    ...profile.languages.map((item) => `- ${item.language}: ${item.proficiency}`),
    "",
    ...(profile.workPreferences?.environment ? [`Work environment preference: ${profile.workPreferences.environment}.`, ""] : []),
    "## Portfolio projects",
    "",
    ...knowledge.projects.flatMap(projectLines),
    "## Completed client work and feedback",
    "",
    `Source: ${upwork.source.profileUrl}`,
    `Snapshot retrieved: ${upwork.source.retrievedAt}`,
    `Upwork display name: ${upwork.profile.displayName}`,
    `Public headline: ${upwork.profile.title}`,
    `Completed jobs: ${upwork.profile.completedJobCount}. Total jobs displayed: ${upwork.profile.totalJobCount}. Written client reviews: ${upwork.profile.writtenReviewCount}.`,
    `The profile displayed ${upwork.profile.badge} and ${upwork.profile.jobSuccessPercent}% Job Success on ${upwork.profile.snapshotDate || upwork.source.retrievedAt}.`,
    "",
    ...knowledge.clientWork.sourceBoundaries.map((boundary) => `- ${boundary}`),
    "",
    ...upwork.completedWork.flatMap((job) => [
      `### ${job.title}`,
      "",
      `Period: ${job.period}`,
      `Client rating: ${job.rating} out of ${job.ratingScale}.`,
      ...(job.clientName ? [`Upwork client account: ${job.clientName}`] : []),
      ...(job.feedback ? ["", "Client feedback:", job.feedback] : ["Client rating provided without written feedback."]),
      `Source: ${job.sourceUrl}`,
      "",
    ]),
    "## Contact and professional links",
    "",
    `- Portfolio: ${absoluteUrl("/")}`,
    `- Contact: ${absoluteUrl("/#contact")}`,
    `- Résumé PDF: ${absoluteUrl("/Lihon-Gebre-Resume.pdf")}`,
    `- Résumé text: ${absoluteUrl("/Lihon-Gebre-Resume.txt")}`,
    `- Email: ${CONTACT_EMAIL}`,
    `- GitHub: ${profile.links.github}`,
    `- LinkedIn: ${profile.links.linkedin}`,
    `- Upwork: ${upwork.source.profileUrl}`,
    "",
  ].join("\n");

  return new Response(text, {
    headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "public, max-age=3600" },
  });
}
